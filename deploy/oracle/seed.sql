-- Demo ERP for Oracle 12c+ (run as the schema owner). Identifiers are UPPERCASE (unquoted);
-- edm-ai quotes identifiers, so config.json must use the same uppercase names.
CREATE TABLE CUSTOMERS(ID NUMBER PRIMARY KEY, NAME VARCHAR2(100), INDUSTRY VARCHAR2(50), CREDIT_GRADE VARCHAR2(10));
CREATE TABLE CONTRACTS(ID VARCHAR2(20) PRIMARY KEY, PROJECT_CODE VARCHAR2(20), CUSTOMER_NAME VARCHAR2(100),
                       AMOUNT NUMBER(18), MARGIN_RATE NUMBER(5,2), DUE_DATE VARCHAR2(10), OWNER_DEPT VARCHAR2(30));
CREATE TABLE INVOICES(ID VARCHAR2(20) PRIMARY KEY, PROJECT_CODE VARCHAR2(20), AMOUNT NUMBER(18), STATUS VARCHAR2(30));
